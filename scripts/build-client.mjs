// Dependency-free bundling of the tested state helpers and the browser entry.
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const state = await readFile(new URL('ui-state.js', root), 'utf8');
const main = await readFile(new URL('client-main.js', root), 'utf8');
if (/^import\s/m.test(state) || /^export\s+(?!function|const|class)/m.test(state)) throw new Error('State helpers must be standalone named declarations');
const bundle = '// Generated by scripts/build-client.mjs. Edit ui-state.js or client-main.js.\n(() => {\n' + state.replace(/^export\s+/gm, '') + '\n' + main + '\n})();\n';
const target = new URL('client.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== bundle) throw new Error('Client bundle is stale; run npm run build');
  console.log('Client bundle matches its sources');
} else {
  await writeFile(target, bundle, 'utf8');
  console.log('Built client.js');
}
